"""
Initial EDA for weather-capture history.

Runs a first-pass exploration across the three data sources and writes:
  - figures/*.png            plots
  - eda_summary.md           a written summary with the key findings

No pandas (unavailable in this env); numpy + matplotlib only.
"""
import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import loaders as L

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")
os.makedirs(FIG, exist_ok=True)

UNITS = {"temperature_2m": "°C", "shortwave_radiation": "W/m²",
         "cloud_cover": "%", "wind_speed_100m": "km/h"}

def parse_times(times):
    """ISO strings -> arrays of hour-of-day and month, plus fractional day index."""
    hod = np.array([int(t[11:13]) for t in times])
    month = np.array([int(t[5:7]) for t in times])
    year = np.array([int(t[0:4]) for t in times])
    return hod, month, year

report = []
def say(s=""):
    print(s)
    report.append(s)

say("# Initial EDA — weather-capture history\n")
say("Generated by `modeling/EDA/eda.py`. Sources: verification actuals, ")
say("previous_runs (ECMWF IFS HRES day-ahead), ensemble_mean archive (3 models).\n")

# ---------------------------------------------------------------------------
# 1. Coverage & completeness
# ---------------------------------------------------------------------------
say("## 1. Coverage & completeness\n")
say("| location | actuals hours | range | prev_runs valid% | ens_mean hours |")
say("|---|---|---|---|---|")
for loc in L.LOCATIONS:
    a = L.load_actuals(loc)
    pr = L.load_previous_runs(loc)
    em = L.load_ensemble_mean(loc, "ncep_gefs025_ensemble_mean")
    av = L.to_float(a["temperature_2m"])
    prv = L.to_float(pr["temperature_2m_previous_day1"])
    valid = 100 * np.mean(~np.isnan(prv))
    say(f"| {loc} | {len(a['time'])} | {a['time'][0][:10]} → {a['time'][-1][:10]} "
        f"| {valid:.1f}% | {len(em['time'])} |")
say("")
say("_previous_runs is null before 2024-02-04 (Jan 2024 empty), 100% populated after. "
    "The usable modeling window with a day-ahead feature is **2024-02-04 → today**._\n")

# ---------------------------------------------------------------------------
# 2. Summary statistics of actuals (all locations)
# ---------------------------------------------------------------------------
say("## 2. Actuals — summary statistics\n")
for v in L.VARS:
    say(f"### {v} ({UNITS[v]})\n")
    say("| location | mean | std | min | p50 | max |")
    say("|---|---|---|---|---|---|")
    for loc in L.LOCATIONS:
        a = L.load_actuals(loc)
        x = L.to_float(a[v]); x = x[~np.isnan(x)]
        say(f"| {loc} | {x.mean():.1f} | {x.std():.1f} | {x.min():.1f} "
            f"| {np.percentile(x,50):.1f} | {x.max():.1f} |")
    say("")

# ---------------------------------------------------------------------------
# 3. Diurnal + seasonal profiles (temperature & solar) — figure
# ---------------------------------------------------------------------------
fig, axes = plt.subplots(2, 2, figsize=(13, 9))
for loc in L.LOCATIONS:
    a = L.load_actuals(loc)
    hod, month, year = parse_times(a["time"])
    # diurnal temp
    t = L.to_float(a["temperature_2m"])
    dm = [np.nanmean(t[hod == h]) for h in range(24)]
    axes[0,0].plot(range(24), dm, label=loc)
    # diurnal solar
    s = L.to_float(a["shortwave_radiation"])
    sm = [np.nanmean(s[hod == h]) for h in range(24)]
    axes[0,1].plot(range(24), sm, label=loc)
    # seasonal temp
    tmo = [np.nanmean(t[month == m]) for m in range(1,13)]
    axes[1,0].plot(range(1,13), tmo, label=loc)
    # seasonal solar
    smo = [np.nanmean(s[month == m]) for m in range(1,13)]
    axes[1,1].plot(range(1,13), smo, label=loc)
axes[0,0].set(title="Diurnal temperature", xlabel="hour (UTC)", ylabel="°C")
axes[0,1].set(title="Diurnal shortwave radiation", xlabel="hour (UTC)", ylabel="W/m²")
axes[1,0].set(title="Seasonal temperature", xlabel="month", ylabel="°C")
axes[1,1].set(title="Seasonal shortwave radiation", xlabel="month", ylabel="W/m²")
for ax in axes.flat:
    ax.legend(fontsize=7); ax.grid(alpha=0.3)
fig.suptitle("Diurnal & seasonal profiles (actuals, all locations)", fontsize=13)
fig.tight_layout()
fig.savefig(os.path.join(FIG, "profiles.png"), dpi=110)
plt.close(fig)
say("## 3. Diurnal & seasonal profiles\n")
say("![profiles](figures/profiles.png)\n")
say("Times are UTC; California/Nevada local is UTC−7/−8, so the temperature "
    "trough near hour 13 UTC and solar peak near hour 20 UTC are the expected "
    "pre-dawn low and local solar noon.\n")

# ---------------------------------------------------------------------------
# 4. Forecast skill: previous_runs day-ahead vs actuals
# ---------------------------------------------------------------------------
say("## 4. Day-ahead forecast skill (previous_runs vs actuals)\n")
say("Aligning the ECMWF IFS HRES day-ahead feature against actuals on the shared "
    "timestamps (2024-02-04 onward). Error = forecast − actual.\n")
say("| location | var | n | bias | MAE | RMSE | corr |")
say("|---|---|---|---|---|---|---|")
skill_fig_data = {}
for loc in L.LOCATIONS:
    a = L.load_actuals(loc); pr = L.load_previous_runs(loc)
    a_idx = {t: i for i, t in enumerate(a["time"])}
    for v in L.VARS:
        pv = L.to_float(pr[v + "_previous_day1"])
        av_full = L.to_float(a[v])
        f, o = [], []
        for i, t in enumerate(pr["time"]):
            j = a_idx.get(t)
            if j is None: continue
            if np.isnan(pv[i]) or np.isnan(av_full[j]): continue
            f.append(pv[i]); o.append(av_full[j])
        f = np.array(f); o = np.array(o)
        if len(f) < 10: continue
        err = f - o
        bias = err.mean(); mae = np.abs(err).mean(); rmse = np.sqrt((err**2).mean())
        corr = np.corrcoef(f, o)[0,1]
        say(f"| {loc} | {v} | {len(f)} | {bias:+.2f} | {mae:.2f} | {rmse:.2f} | {corr:.3f} |")
        if v == "temperature_2m":
            skill_fig_data[loc] = (o, f)
    say("")

# scatter of temp forecast vs actual for one location
if skill_fig_data:
    fig, axes = plt.subplots(1, len(skill_fig_data), figsize=(4*len(skill_fig_data), 4), squeeze=False)
    for ax, (loc, (o, f)) in zip(axes[0], skill_fig_data.items()):
        ax.scatter(o, f, s=1, alpha=0.15)
        lim = [min(o.min(), f.min()), max(o.max(), f.max())]
        ax.plot(lim, lim, "r--", lw=1)
        ax.set(title=loc, xlabel="actual °C", ylabel="forecast °C")
        ax.grid(alpha=0.3)
    fig.suptitle("Day-ahead temperature: forecast vs actual", fontsize=13)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "forecast_vs_actual_temp.png"), dpi=110)
    plt.close(fig)
    say("![forecast vs actual](figures/forecast_vs_actual_temp.png)\n")

# ---------------------------------------------------------------------------
# 5. Ensemble spread — does the archive spread track forecast uncertainty?
# ---------------------------------------------------------------------------
say("## 5. Ensemble mean/spread (archive)\n")
say("Mean spread by model & variable over the ~93-day archive window (Fresno). "
    "Spread is the ensemble's own uncertainty estimate.\n")
say("| model | temp spread | solar spread | cloud spread | wind spread |")
say("|---|---|---|---|---|")
for m in L.ENSEMBLE_MODELS:
    em = L.load_ensemble_mean("fresno-ca", m)
    if em is None: continue
    vals = []
    for v in L.VARS:
        sp = L.to_float(em[v + "_spread"])
        mv = np.nanmean(sp) if np.any(~np.isnan(sp)) else np.nan
        vals.append("—" if np.isnan(mv) else f"{mv:.2f}")
    short = m.replace("_ensemble_mean","").replace("_seamless","")
    say(f"| {short} | {vals[0]} | {vals[1]} | {vals[2]} | {vals[3]} |")
say("")
say("_**Data-availability finding:** `wind_speed_100m` (and its spread) is entirely "
    "null for DWD ICON and GFS in the ensemble_mean archive — only ECMWF IFS "
    "provides 100 m wind here. The other three variables are present for all three "
    "models. Anything using ensemble 100 m wind as a feature must rely on ECMWF, or "
    "fall back to a lower level._\n")

# ---------------------------------------------------------------------------
# 6. Export analysis-ready CSVs
# ---------------------------------------------------------------------------
import csv
CSVDIR = os.path.join(HERE, "csv")
os.makedirs(CSVDIR, exist_ok=True)

# 6a. Long actuals table: time, location, + 4 vars
p = os.path.join(CSVDIR, "actuals_hourly.csv")
with open(p, "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["time", "location"] + L.VARS)
    for loc in L.LOCATIONS:
        a = L.load_actuals(loc)
        cols = [a[v] for v in L.VARS]
        for i, t in enumerate(a["time"]):
            w.writerow([t, loc] + [cols[k][i] for k in range(len(L.VARS))])

# 6b. Aligned feature+label table (temp only, the flagship): time, location, forecast, actual, error
p2 = os.path.join(CSVDIR, "temp_forecast_vs_actual.csv")
with open(p2, "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["time", "location", "forecast_temp", "actual_temp", "error"])
    for loc in L.LOCATIONS:
        a = L.load_actuals(loc); pr = L.load_previous_runs(loc)
        a_idx = {t: i for i, t in enumerate(a["time"])}
        pv = pr["temperature_2m_previous_day1"]; av = a["temperature_2m"]
        for i, t in enumerate(pr["time"]):
            j = a_idx.get(t)
            if j is None or pv[i] is None or av[j] is None: continue
            w.writerow([t, loc, pv[i], av[j], round(pv[i]-av[j], 3)])

say("## 6. CSV exports\n")
say("Analysis-ready CSVs written to `modeling/EDA/csv/`:\n")
say("- `actuals_hourly.csv` — long table: time, location, 4 actual variables.")
say("- `temp_forecast_vs_actual.csv` — aligned day-ahead temp forecast, actual, and error per timestamp/location.\n")

# ---------------------------------------------------------------------------
# write report
# ---------------------------------------------------------------------------
with open(os.path.join(HERE, "eda_summary.md"), "w") as fh:
    fh.write("\n".join(report) + "\n")
print("\n=== wrote eda_summary.md and figures/ ===")
