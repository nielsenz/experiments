"""
Demand vs weather join — the first look at CAISO demand as a function of weather.

Joins CAISO hourly demand (label) against the actuals weather series (features)
on UTC timestamps, then explores the relationships that make this an
energy-prediction dataset:

  1. demand-temperature response curve (the U/hockey-stick from heating + AC)
  2. diurnal & seasonal demand profiles (local time)
  3. how a state-average temperature relates to system demand
  4. correlation of each weather variable with demand

Writes figures/ and appends findings to join_summary.md.

Demand is CAISO-system-wide (one series). Weather is per-location; for a
system-level view we use a simple population-weighted-ish average across the
five captured cities (equal weight here — a deliberate first-pass simplification;
the five sites bracket the big CA/NV load centers).
"""
import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import loaders as L

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")
os.makedirs(FIG, exist_ok=True)

report = []
def say(s=""):
    print(s); report.append(s)

say("# Demand vs weather — first join\n")
say("Generated by `modeling/EDA/join_demand_weather.py`. CAISO system demand "
    "(EIA) joined to actuals weather on UTC hours.\n")

# ---------------------------------------------------------------------------
# Build aligned arrays
# ---------------------------------------------------------------------------
demand = L.load_caiso_demand()          # {utc_key -> MWh or None}

# State-average weather across the 5 cities, per UTC hour.
# Collect each variable into {utc_key -> [values across cities]}.
weather = {v: {} for v in L.VARS}
for loc in L.LOCATIONS:
    a = L.load_actuals(loc)
    for i, t in enumerate(a["time"]):
        for v in L.VARS:
            val = a[v][i]
            if val is None:
                continue
            weather[v].setdefault(t, []).append(float(val))

# Common hours present in demand AND all weather vars.
common = []
for k in sorted(demand):
    if demand[k] is None:
        continue
    if all(k in weather[v] and len(weather[v][k]) == len(L.LOCATIONS) for v in L.VARS):
        common.append(k)

say(f"Aligned hours (demand + full 5-city weather): **{len(common)}** "
    f"({common[0]} → {common[-1]}).\n")

dem = np.array([demand[k] for k in common])
wx = {v: np.array([np.mean(weather[v][k]) for k in common]) for v in L.VARS}
hod_utc = np.array([int(k[11:13]) for k in common])
hod_loc = np.array([L.local_hour(k) for k in common])
month = np.array([int(k[5:7]) for k in common])

# ---------------------------------------------------------------------------
# 1. Demand vs temperature response curve
# ---------------------------------------------------------------------------
say("## 1. Demand–temperature response curve\n")
T = wx["temperature_2m"]
# bin temperature, show mean demand per bin
bins = np.arange(np.floor(T.min()), np.ceil(T.max()) + 2, 2)
idx = np.digitize(T, bins)
centers, means, p10, p90 = [], [], [], []
for b in range(1, len(bins)):
    m = idx == b
    if m.sum() < 20:
        continue
    centers.append((bins[b-1] + bins[b]) / 2)
    means.append(dem[m].mean())
    p10.append(np.percentile(dem[m], 10))
    p90.append(np.percentile(dem[m], 90))
centers = np.array(centers); means = np.array(means)

fig, ax = plt.subplots(figsize=(8, 5))
ax.scatter(T, dem, s=1, alpha=0.05, color="gray")
ax.fill_between(centers, p10, p90, alpha=0.2, label="10–90th pct")
ax.plot(centers, means, "r-o", ms=4, label="mean demand")
ax.set(xlabel="state-avg temperature (°C)", ylabel="CAISO demand (MWh)",
       title="Demand–temperature response")
ax.legend(); ax.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "demand_vs_temp.png"), dpi=110)
plt.close(fig)
say("![demand vs temp](figures/demand_vs_temp.png)\n")

# quantify the two limbs
tmin_i = int(np.argmin(means))
say(f"Minimum-demand temperature ≈ **{centers[tmin_i]:.0f} °C** "
    f"({means[tmin_i]:.0f} MWh). Demand rises on both sides — the classic "
    f"U-shape from heating below and cooling (AC) above.\n")
# cooling slope (upper limb) via simple fit on T>min
up = centers > centers[tmin_i]
if up.sum() >= 2:
    slope = np.polyfit(centers[up], means[up], 1)[0]
    say(f"Cooling-side sensitivity ≈ **{slope:.0f} MWh per °C** above the "
        f"minimum — the AC-driven limb, which is where summer forecast error "
        f"costs the most.\n")

# ---------------------------------------------------------------------------
# 2. Diurnal & seasonal demand profiles (local time)
# ---------------------------------------------------------------------------
fig, axes = plt.subplots(1, 2, figsize=(13, 5))
dm = [dem[hod_loc == h].mean() for h in range(24)]
axes[0].plot(range(24), dm, "-o", ms=3)
axes[0].set(title="Diurnal demand (local time, ~PST)", xlabel="local hour", ylabel="MWh")
axes[0].grid(alpha=0.3)
mm = [dem[month == m].mean() for m in range(1, 13)]
axes[1].plot(range(1, 13), mm, "-o", ms=4, color="darkorange")
axes[1].set(title="Seasonal demand", xlabel="month", ylabel="MWh")
axes[1].grid(alpha=0.3)
fig.suptitle("CAISO demand profiles", fontsize=13)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "demand_profiles.png"), dpi=110)
plt.close(fig)
say("## 2. Diurnal & seasonal demand profiles\n")
say("![demand profiles](figures/demand_profiles.png)\n")
peak_h = int(np.argmax(dm)); trough_h = int(np.argmin(dm))
say(f"Demand peaks around **{peak_h:02d}:00 local** ({dm[peak_h]:.0f} MWh) and "
    f"troughs near **{trough_h:02d}:00** ({dm[trough_h]:.0f} MWh) — the evening "
    f"AC+lighting ramp vs pre-dawn low. Seasonally, the summer cooling peak "
    f"(month {int(np.argmax(mm))+1}) dominates.\n")

# ---------------------------------------------------------------------------
# 3. Correlations of weather vars with demand
# ---------------------------------------------------------------------------
say("## 3. Weather–demand correlation (state-avg, whole series)\n")
say("| variable | corr with demand |")
say("|---|---|")
for v in L.VARS:
    c = np.corrcoef(wx[v], dem)[0, 1]
    say(f"| {v} | {c:+.3f} |")
say("")
say("_Raw hourly correlation mixes the diurnal cycle of both signals; the "
    "response curve in §1 is the cleaner read on the physical relationship. "
    "Temperature's signal is U-shaped, so a linear correlation understates it — "
    "cooling-degree / heating-degree features will matter in modeling._\n")

# ---------------------------------------------------------------------------
# 4. Cooling-degree quick check: demand vs CDD-like term
# ---------------------------------------------------------------------------
base = centers[tmin_i]
cdd = np.maximum(T - base, 0)   # cooling degrees above the comfort minimum
hdd = np.maximum(base - T, 0)   # heating degrees below
c_cdd = np.corrcoef(cdd, dem)[0, 1]
c_hdd = np.corrcoef(hdd, dem)[0, 1]
say("## 4. Degree-day features (base = response minimum)\n")
say(f"Using base **{base:.0f} °C**: cooling-degrees corr with demand "
    f"**{c_cdd:+.3f}**, heating-degrees **{c_hdd:+.3f}**. Cooling dominates in "
    f"this CA/NV footprint, as expected — the AC load is the big weather-driven "
    f"swing. These degree-day transforms are the natural first features.\n")

with open(os.path.join(HERE, "join_summary.md"), "w") as fh:
    fh.write("\n".join(report) + "\n")
print("\n=== wrote join_summary.md + figures ===")
